-- Person and Client with JOINED inheritance (ADR-006). SPEC §7.
CREATE TABLE person (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    gender         VARCHAR(10)  NOT NULL CONSTRAINT ck_person_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    age            SMALLINT     NOT NULL CONSTRAINT ck_person_age CHECK (age BETWEEN 0 AND 120),
    identification VARCHAR(20)  NOT NULL CONSTRAINT uk_person_identification UNIQUE,
    address        VARCHAR(200) NOT NULL,
    phone          VARCHAR(16)  NOT NULL,
    -- Optimistic locking and event ordering (ADR-010). Hibernate requires it on the root table.
    version        BIGINT       NOT NULL
);

CREATE TABLE client (
    person_id BIGINT       PRIMARY KEY CONSTRAINT fk_client_person REFERENCES person (id) ON DELETE CASCADE,
    client_id UUID         NOT NULL CONSTRAINT uk_client_client_id UNIQUE,
    password  VARCHAR(100) NOT NULL,
    active    BOOLEAN      NOT NULL
);
