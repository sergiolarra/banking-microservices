-- accounts-service schema (SPEC §7).

-- Local replica of the clients of clients-service, fed by events (ADR-008).
CREATE TABLE client_snapshot (
    client_id      UUID         PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    identification VARCHAR(20)  NOT NULL,
    active         BOOLEAN      NOT NULL,
    deleted        BOOLEAN      NOT NULL,
    version        BIGINT       NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL
);

-- Ids of the client events already applied, for idempotent consumption (ADR-010).
CREATE TABLE processed_event (
    event_id     UUID        PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE account (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number    VARCHAR(10)   NOT NULL CONSTRAINT uk_account_account_number UNIQUE,
    account_type      VARCHAR(10)   NOT NULL CONSTRAINT ck_account_type CHECK (account_type IN ('SAVINGS', 'CHECKING')),
    initial_balance   NUMERIC(15,2) NOT NULL CONSTRAINT ck_account_initial_balance CHECK (initial_balance >= 0),
    -- Last line of defense against a negative balance (ADR-013)
    available_balance NUMERIC(15,2) NOT NULL CONSTRAINT ck_account_available_balance CHECK (available_balance >= 0),
    active            BOOLEAN       NOT NULL,
    -- Local FK: the replica lives in this database, so it does not cross services
    client_id         UUID          NOT NULL CONSTRAINT fk_account_client REFERENCES client_snapshot (client_id),
    version           BIGINT        NOT NULL
);

CREATE INDEX ix_account_client_id ON account (client_id);

CREATE TABLE movement (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT        NOT NULL CONSTRAINT fk_movement_account REFERENCES account (id),
    movement_date TIMESTAMPTZ   NOT NULL,
    movement_type VARCHAR(10)   NOT NULL CONSTRAINT ck_movement_type CHECK (movement_type IN ('DEPOSIT', 'WITHDRAWAL')),
    amount        NUMERIC(15,2) NOT NULL CONSTRAINT ck_movement_amount CHECK (amount <> 0),
    balance       NUMERIC(15,2) NOT NULL CONSTRAINT ck_movement_balance CHECK (balance >= 0),
    -- The sign decides the type (ADR-012)
    CONSTRAINT ck_movement_type_matches_sign CHECK ((movement_type = 'DEPOSIT') = (amount > 0))
);

-- Statement by date range and latest movement of an account (F4, F2-AC8)
CREATE INDEX ix_movement_account_date ON movement (account_id, movement_date, id);
